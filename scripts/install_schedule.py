# -*- coding: utf-8 -*-
"""Generate a portable five-minute watcher; --install explicitly registers a Windows task."""
import argparse
import datetime
import getpass
import json
import os
from pathlib import Path
import shlex
import subprocess
import sys
import xml.etree.ElementTree as ET

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
MARKER = "PhoneQuickCut managed task v1"
TASK_NS = "http://schemas.microsoft.com/windows/2004/02/mit/task"
RUNNER = '''# Generated by phone-quick-cut/scripts/install_schedule.py
import json
import os
from pathlib import Path
import subprocess
import sys

base = Path(__file__).resolve().parent
config = json.loads((base / "config.json").read_text(encoding="utf-8"))
env = {**os.environ, **config["environment"], "PYTHONUTF8": "1"}
command = [sys.executable, "-X", "utf8", str(Path(config["repository"]) / "scripts" / "watch_inbox.py"), "--once", "--agent", config["agent"]]
with open(base / "watch.log", "a", encoding="utf-8") as log:
    result = subprocess.run(command, cwd=config["repository"], env=env, stdout=log, stderr=subprocess.STDOUT)
raise SystemExit(result.returncode)
'''


def vbs_string(value):
    """Keep generated WScript sources ASCII even when Python/repository paths contain CJK."""
    pieces, plain = [], []
    for ch in str(value):
        if 32 <= ord(ch) < 127:
            plain.append(ch)
        else:
            if plain:
                pieces.append('"' + ''.join(plain).replace('"', '""') + '"')
                plain = []
            for i in range(0, len(ch.encode("utf-16-le")), 2):
                code = int.from_bytes(ch.encode("utf-16-le")[i:i + 2], "little")
                pieces.append(f"ChrW({code})")
    if plain:
        pieces.append('"' + ''.join(plain).replace('"', '""') + '"')
    return " & ".join(pieces) or '""'


def task_xml(vbs_path, repository, start=None):
    ET.register_namespace("", TASK_NS)
    def child(parent, name, text=None, **attrib):
        node = ET.SubElement(parent, f"{{{TASK_NS}}}{name}", attrib)
        node.text = text
        return node
    task = ET.Element(f"{{{TASK_NS}}}Task", {"version": "1.2"})
    registration = child(task, "RegistrationInfo")
    child(registration, "Description", MARKER)
    triggers = child(task, "Triggers")
    trigger = child(triggers, "TimeTrigger")
    repetition = child(trigger, "Repetition")
    child(repetition, "Interval", "PT5M")
    child(repetition, "StopAtDurationEnd", "false")
    when = start or (datetime.datetime.now().astimezone() + datetime.timedelta(minutes=1)).replace(microsecond=0)
    child(trigger, "StartBoundary", when.isoformat())
    child(trigger, "Enabled", "true")
    principals = child(task, "Principals")
    principal = child(principals, "Principal", id="Author")
    user = os.environ.get("USERNAME") or getpass.getuser()
    domain = os.environ.get("USERDOMAIN")
    child(principal, "UserId", f"{domain}\\{user}" if domain else user)
    child(principal, "LogonType", "InteractiveToken")
    child(principal, "RunLevel", "LeastPrivilege")
    settings = child(task, "Settings")
    child(settings, "MultipleInstancesPolicy", "IgnoreNew")
    child(settings, "DisallowStartIfOnBatteries", "false")
    child(settings, "StopIfGoingOnBatteries", "false")
    child(settings, "StartWhenAvailable", "true")
    child(settings, "Hidden", "true")
    child(settings, "ExecutionTimeLimit", "PT3H")
    actions = child(task, "Actions", Context="Author")
    action = child(actions, "Exec")
    windir = Path(os.environ.get("WINDIR", r"C:\Windows"))
    child(action, "Command", str(windir / "System32" / "wscript.exe"))
    child(action, "Arguments", '"' + str(vbs_path) + '"')
    child(action, "WorkingDirectory", str(repository))
    return ET.tostring(task, encoding="utf-16", xml_declaration=True)


def generate(output, agent="codex", repository=ROOT, python=None):
    from pqc_common import INBOX, OUTBOX, VIDEO_ROOT
    output = Path(output).expanduser().resolve()
    repository = Path(repository).resolve()
    python = str(Path(python or sys.executable).resolve())
    for path in [str(output), str(repository), python]:
        if any(ch in path for ch in ("\n", "\r", '"')):
            raise ValueError("Paths containing newlines or double quotes are unsupported for scheduling.")
    if output.exists() and any(output.iterdir()):
        previous = output / "config.json"
        try:
            owned = json.loads(previous.read_text(encoding="utf-8")).get("managed_by") == MARKER
        except (OSError, ValueError, AttributeError):
            owned = False
        if not owned:
            raise ValueError("Refusing to overwrite an unowned nonempty output directory.")
    output.mkdir(parents=True, exist_ok=True)
    # Capture path/provider preferences, never API credentials or secrets.
    env = {k: v for k, v in os.environ.items() if k.startswith("PQC_") and not any(s in k.upper() for s in ("KEY", "TOKEN", "SECRET", "PASSWORD"))}
    # Cron/Task Scheduler do not inherit an interactive shell's Homebrew/CLI PATH.
    env["PATH"] = os.environ.get("PATH", os.defpath)
    env.update(PQC_INBOX=str(INBOX.resolve()), PQC_OUTBOX=str(OUTBOX.resolve()), PQC_VIDEO=str(VIDEO_ROOT.resolve()))
    config = {"managed_by": MARKER, "repository": str(repository), "python": python, "agent": agent, "environment": env}
    (output / "config.json").write_text(json.dumps(config, ensure_ascii=False, indent=2), encoding="utf-8")
    (output / "runner.py").write_text(RUNNER, encoding="utf-8")
    script = ("' Generated watcher; ASCII only.\r\nSet sh = CreateObject(\"WScript.Shell\")\r\n"
              f"python = {vbs_string(python)}\r\nrunner = {vbs_string(output / 'runner.py')}\r\n"
              'cmd = Chr(34) & python & Chr(34) & " -X utf8 " & Chr(34) & runner & Chr(34)\r\n'
              "WScript.Quit sh.Run(cmd, 0, True)\r\n")
    (output / "run_watch.vbs").write_bytes(script.encode("ascii"))
    shell = "#!/bin/sh\nexec " + shlex.quote(python) + " -X utf8 " + shlex.quote(str(output / "runner.py")) + "\n"
    (output / "run_watch.sh").write_text(shell, encoding="utf-8")
    if os.name != "nt":
        (output / "run_watch.sh").chmod(0o700)
    (output / "task.xml").write_bytes(task_xml(output / "run_watch.vbs", repository))
    return output


def register_windows_task(output, name="PhoneQuickCut", replace=False):
    if os.name != "nt":
        raise RuntimeError("Automatic registration is Windows-only. Add the printed crontab line yourself on macOS/Linux.")
    query = subprocess.run(["schtasks", "/Query", "/TN", name, "/XML"], capture_output=True, text=True, encoding="utf-8", errors="replace")
    exists = query.returncode == 0
    if exists:
        try:
            tree = ET.fromstring(query.stdout)
            description = tree.find(f"{{{TASK_NS}}}RegistrationInfo/{{{TASK_NS}}}Description")
            owned = description is not None and description.text == MARKER
        except ET.ParseError:
            owned = False
        if not (replace and owned):
            raise RuntimeError("Task already exists. It can only be replaced with --replace when its ownership marker belongs to phone-quick-cut.")
    command = ["schtasks", "/Create", "/TN", name, "/XML", str(Path(output) / "task.xml")]
    if exists:
        command.append("/F")
    subprocess.run(command, check=True)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--output", type=Path, default=ROOT / ".pqc-schedule")
    ap.add_argument("--agent", choices=("claude", "codex"), default="codex")
    ap.add_argument("--install", action="store_true", help="Explicitly register a Windows task for the current logged-in user.")
    ap.add_argument("--replace", action="store_true", help="Allow replacing an existing task marked as phone-quick-cut-owned.")
    ap.add_argument("--task-name", default="PhoneQuickCut")
    args = ap.parse_args(argv)
    try:
        if args.replace and not args.install:
            ap.error("--replace requires --install")
        out = generate(args.output, args.agent)
        print(f"Generated {out}; Python: {sys.executable}; Agent: {args.agent}")
        if args.install:
            register_windows_task(out, args.task_name, args.replace)
            print(f"Registered Windows task {args.task_name} (every five minutes, while signed in).")
        else:
            print("No scheduled task was installed. Windows: rerun with --install after reviewing the generated files.")
        cron = "/bin/sh " + shlex.quote(str(out / "run_watch.sh"))
        print("macOS/Linux crontab (install manually): */5 * * * * " + cron.replace("%", r"\%"))
        return 0
    except (OSError, RuntimeError, ValueError, subprocess.CalledProcessError) as exc:
        print(f"[schedule] {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
